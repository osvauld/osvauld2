-- Bakes demo_apps/brawl/moves.lua into moves_baked.lua (docs/design/brawl-fighting.md decision 2):
-- per move, per move tick, the live circles { x, y, r, window } from the feet, facing right, +y
-- down, on the 1/8 grid; each move's `reach` box { x0, y0, x1, y1 }; and the angle table, each
-- used angle (and the mirror 360 - a of a downward one) as a vector rounded to 1/256, y up. The
-- rules never run trig: this script does, at authoring time.
-- A circle rides its part: `at` is a point of the setup drawing on that part, carried by the move's
-- clip (author.lua's FK) at the frame move tick k shows (act_t = k - 1, look.lua's quantizing), then
-- placed as look.lua places the robot: a ground move's sole on the feet line, an aerial's root pivot,
-- x Look.SCALE.
--   lua scripts/bake_brawl_moves.lua               -- writes the file
--   lua scripts/bake_brawl_moves.lua --stdout      -- prints it (the hitbox test compares the two)
--   lua scripts/bake_brawl_moves.lua --dump MOVE   -- per tick: frame time, circles in drawing units, soles
-- Required as a module (by the hitbox test), it only returns its functions.
package.path = "demo_apps/brawl/?.lua;" .. package.path
local Look = require("look")
local A = require("characters/robot/author")
local scout = require("characters/robot/scout")
local B = {}
B.OUT = "demo_apps/brawl/moves_baked.lua"

local function grid(v, n) return math.floor(v * n + 0.5) / n end
local function num(v) return string.format("%.17g", v) end
local ROOT = A.parts.root.pivot

local setup_world = A.world(A.setup_pose())
local function inverse(m)
	local det = m[1] * m[4] - m[2] * m[3]
	local a, b, c, d = m[4] / det, -m[2] / det, -m[3] / det, m[1] / det
	return { a, b, c, d, -(a * m[5] + c * m[6]), -(b * m[5] + d * m[6]) }
end
local function apply(m, x, y) return m[1] * x + m[3] * y + m[5], m[2] * x + m[4] * y + m[6] end

function B.clip(name) return dofile("demo_apps/brawl/" .. Look.OWN_DIR .. name .. ".lua") end

-- Move tick k's frame of `clip`: the pose, the circles' drawing points { dx, dy } per circle of
-- each live window, and the feet line (drawing y).
function B.frame(m, clip, k)
	local time = Look.at({ length = clip.length, loop = clip.loop }, k - 1).time
	local pose = A.at(clip, time)
	local world = A.world(pose)
	local feet = m.air and ROOT[2] or Look.sole(scout, pose)
	local live = {}
	for wi, w in ipairs(m.windows) do
		if k >= w.from and k <= w.to then
			for _, c in ipairs(w.circles) do
				assert(A.parts[c.part], "moves." .. m.name .. ": no part " .. tostring(c.part))
				local lx, ly = apply(inverse(setup_world(c.part)), c.at[1], c.at[2])
				local dx, dy = apply(world(c.part), lx, ly)
				live[#live + 1] = { dx = dx, dy = dy, r = c.r, w = wi }
			end
		end
	end
	return { time = time, pose = pose, feet = feet, live = live }
end

-- The bake: { angles = { { deg, x, y } }, moves = { [name] = { reach, ticks } }, text }.
function B.bake(moves, clip_of)
	clip_of = clip_of or B.clip
	local names = {}
	for name in pairs(moves) do names[#names + 1] = name end
	table.sort(names)
	local used = {}
	for _, name in ipairs(names) do
		for _, w in ipairs(moves[name].windows) do
			used[w.angle] = true
			if w.angle > 180 and w.angle < 360 then used[360 - w.angle] = true end
		end
	end
	local degs = {}
	for a in pairs(used) do degs[#degs + 1] = a end
	table.sort(degs)

	local out = { angles = {}, moves = {} }
	local lines = {}
	local function put(s) lines[#lines + 1] = s end
	put("-- Generated by scripts/bake_brawl_moves.lua from moves.lua and the move clips. Do not edit; rebake.")
	put("-- ticks[k] = the circles live on move tick k: { x, y, r, window }, from the feet, facing right, +y down.")
	put("return {")
	put("\tangles = { -- { degrees, x, y }: the launch direction, y up, rounded to 1/256")
	for _, a in ipairs(degs) do
		local r = math.rad(a)
		local v = { a, grid(math.cos(r), 256), grid(math.sin(r), 256) }
		out.angles[#out.angles + 1] = v
		put("\t\t{ " .. num(v[1]) .. ", " .. num(v[2]) .. ", " .. num(v[3]) .. " },")
	end
	put("\t},")
	put("\tmoves = {")
	for _, name in ipairs(names) do
		local m = moves[name]
		m.name = name
		local clip = clip_of(m.clip)
		local total = m.startup + m.active + m.recovery
		local x0, y0, x1, y1 = math.huge, math.huge, -math.huge, -math.huge
		local ticks, strs = {}, {}
		for k = 1, total do
			local fr = B.frame(m, clip, k)
			local cs, ss = {}, {}
			for _, c in ipairs(fr.live) do
				local x, y, r = grid((c.dx - ROOT[1]) * Look.SCALE, 8), grid((c.dy - fr.feet) * Look.SCALE, 8), grid(c.r, 8)
				cs[#cs + 1] = { x, y, r, c.w }
				ss[#ss + 1] = "{ " .. num(x) .. ", " .. num(y) .. ", " .. num(r) .. ", " .. c.w .. " }"
				x0, y0, x1, y1 = math.min(x0, x - r), math.min(y0, y - r), math.max(x1, x + r), math.max(y1, y + r)
			end
			ticks[k] = cs
			strs[k] = #ss == 0 and "{}" or "{ " .. table.concat(ss, ", ") .. " }"
		end
		m.name = nil
		local reach = { x0, y0, x1, y1 }
		out.moves[name] = { reach = reach, ticks = ticks }
		put("\t\t" .. name .. " = {")
		put("\t\t\treach = { " .. num(x0) .. ", " .. num(y0) .. ", " .. num(x1) .. ", " .. num(y1) .. " },")
		put("\t\t\tticks = {")
		for k = 1, total do put("\t\t\t\t" .. strs[k] .. ", -- " .. k) end
		put("\t\t\t},")
		put("\t\t},")
	end
	put("\t},")
	put("}")
	out.text = table.concat(lines, "\n") .. "\n"
	return out
end

-- The first difference between two bakes' moves (moves_baked.lua's and a fresh one), naming the
-- move and the tick; nil when equal.
function B.diff(have, want)
	local names = {}
	for name in pairs(want) do names[#names + 1] = name end
	table.sort(names)
	for _, name in ipairs(names) do
		local h, w = have[name], want[name]
		if not h then return name .. ": not baked" end
		if #h.ticks ~= #w.ticks then return name .. ": " .. #h.ticks .. " ticks baked, " .. #w.ticks .. " now" end
		for k = 1, #w.ticks do
			local a, b = h.ticks[k], w.ticks[k]
			local same = #a == #b
			for i = 1, same and #b or 0 do
				for j = 1, 4 do
					if a[i][j] ~= b[i][j] then same = false end
				end
			end
			if not same then return name .. " tick " .. k .. ": the clip has moved since the bake (rebake)" end
		end
		for j = 1, 4 do
			if h.reach[j] ~= w.reach[j] then return name .. ": reach differs" end
		end
	end
	return nil
end

local function main()
	local moves = require("moves")
	if arg[1] == "--dump" then
		local name = arg[2]
		local m = assert(moves[name], "no move " .. tostring(name))
		m.name = name
		local clip = B.clip(m.clip)
		for k = 1, m.startup + m.active + m.recovery do
			local fr = B.frame(m, clip, k)
			local cs = {}
			for _, c in ipairs(fr.live) do cs[#cs + 1] = string.format("%.2f %.2f %.2f", c.dx, c.dy, c.r / Look.SCALE) end
			local soles = {}
			for _, id in ipairs(Look.SOLES) do
				local only = { id }
				local save = Look.SOLES
				Look.SOLES = only
				soles[#soles + 1] = string.format("%.2f", Look.sole(scout, fr.pose) - ROOT[2])
				Look.SOLES = save
			end
			print(string.format("tick %d time %.6f feet %.2f soles %s circles %s", k, fr.time, fr.feet, table.concat(soles, " "),
				table.concat(cs, " | ")))
		end
		return
	end
	local text = B.bake(moves).text
	if arg[1] == "--stdout" then
		io.write(text)
	else
		local f = assert(io.open(B.OUT, "w"))
		f:write(text)
		f:close()
		local n = 0
		for _ in pairs(moves) do n = n + 1 end
		print("baked " .. n .. " moves into " .. B.OUT)
	end
end

if arg and arg[0] and arg[0]:match("bake_brawl_moves%.lua$") then main() end
return B
